
public class Calculator {
	
	public int addNum(int a, int b) {
		return a+b;
	}
	public int addNum(int a, int b, int c) {
		return a+b+c;
	}
	public int addNum(int a, int b, int c, int d) {
		return a+b+c+d;
	}
	
	public int mulNum(int a, int b) {
		return a*b;
	}
	public int mulNum(int a, int b, int c) {
		return a*b*c;
	}
	public int mulNum(int a, int b, int c, int d) {
		return a*b*c*d;
	}
}
